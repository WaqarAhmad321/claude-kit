#!/usr/bin/env node
// Print Mongoose models as SCHEMA.md markdown: fields, relations and indexes.
//
// Run it from the project root, after `pnpm install` in server/, so the model files import cleanly:
//
//   KIT_OUT_DIR=.claude/skills/_draft node ${CLAUDE_PLUGIN_ROOT}/scripts/mongoose_model_dump.mjs
//
// KIT_MODELS_DIR picks the directory to import every model file from (default: server/src/models), and
// Mongoose comes from that directory's package, as the model files import it. Each file's import must
// register its model with mongoose.model(name, schema) as a side effect, the way the project's own code
// does. The models print as one document; KIT_OUT_DIR=<dir> writes <dir>/<kebab-case model name>/SCHEMA.md
// per model instead. Exits 2 when no model file is found, Mongoose isn't installed for them, or a model
// file fails to import.

import { readdir } from "node:fs/promises";
import { createRequire } from "node:module";
import { extname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const MODELS_DIR_ENV = "KIT_MODELS_DIR";
const OUT_DIR_ENV = "KIT_OUT_DIR";
const DEFAULT_MODELS_DIR = "server/src/models";
const SCHEMA_FILENAME = "SCHEMA.md";
const EXIT_USAGE_ERROR = 2;
const PROG = "mongoose_model_dump";
const MODEL_EXTENSIONS = new Set([".ts", ".mts", ".js", ".mjs"]);
const RUN_COMMAND = "node ${CLAUDE_PLUGIN_ROOT}/scripts/mongoose_model_dump.mjs";

class UsageError extends Error {}

async function main() {
  let mongoose;
  try {
    const dir = resolve(process.env[MODELS_DIR_ENV] || DEFAULT_MODELS_DIR);
    const files = await modelFiles(dir);
    mongoose = await importMongoose(dir);
    await importModels(files);
  } catch (error) {
    if (error instanceof UsageError) {
      process.stderr.write(`${PROG}: ${error.message}\n`);
      return EXIT_USAGE_ERROR;
    }
    throw error;
  }
  const models = Object.values(mongoose.models).sort((a, b) => a.modelName.localeCompare(b.modelName));
  if (models.length === 0) {
    throw new UsageError(`no model registered itself with mongoose.model(). Point ${MODELS_DIR_ENV} at the right directory.`);
  }
  const outDir = process.env[OUT_DIR_ENV];
  if (!outDir) {
    process.stdout.write(renderDocument(models));
    return 0;
  }
  const { mkdir, writeFile } = await import("node:fs/promises");
  for (const model of models) {
    const target = join(outDir, kebabCase(model.modelName), SCHEMA_FILENAME);
    await mkdir(join(outDir, kebabCase(model.modelName)), { recursive: true });
    await writeFile(target, renderDocument([model]), "utf-8");
    console.log(target);
  }
  return 0;
}

async function modelFiles(dir) {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    throw new UsageError(`${dir} doesn't exist. Point ${MODELS_DIR_ENV} at the project's models directory.`);
  }
  const files = entries
    .filter((entry) => entry.isFile() && MODEL_EXTENSIONS.has(extname(entry.name)))
    .map((entry) => join(dir, entry.name))
    .sort();
  if (files.length === 0) {
    throw new UsageError(`no model files (${[...MODEL_EXTENSIONS].join(", ")}) in ${dir}.`);
  }
  return files;
}

// Resolved from the models' directory, as their own `import "mongoose"` is, so both reach the same copy and its
// model registry: a bare import here would resolve from plugins/kit/scripts/, and the project root of a MERN repo
// has no node_modules of its own.
async function importMongoose(dir) {
  const modelsRequire = createRequire(pathToFileURL(join(dir, "models.js")).href);
  let path;
  try {
    path = modelsRequire.resolve("mongoose");
  } catch (error) {
    if (error?.code !== "MODULE_NOT_FOUND") throw error;
    throw new UsageError(`mongoose isn't installed for ${dir}. Install its package's dependencies first, such as pnpm install in server/.`);
  }
  return (await import(pathToFileURL(path).href)).default;
}

async function importModels(files) {
  for (const file of files) {
    try {
      await import(pathToFileURL(file).href);
    } catch (error) {
      throw new UsageError(`importing ${file} failed: ${error.message}`);
    }
  }
}

function renderDocument(models) {
  const names = models.map((model) => model.modelName).join(", ");
  const lines = [
    `<!-- GENERATED by mongoose_model_dump.mjs; do not edit. Regenerate: ${RUN_COMMAND} -->`,
    `# Schema: ${names}`,
  ];
  for (const model of models) {
    lines.push("", ...modelLines(model));
  }
  return lines.join("\n") + "\n";
}

function modelLines(model) {
  const schema = model.schema;
  const lines = [`## ${model.modelName}`, `Collection: \`${model.collection.collectionName}\``];
  const entries = Object.entries(schema.paths).filter(([name]) => name !== "__v");
  const fields = entries.filter(([, type]) => !refTarget(type));
  const relations = entries.filter(([, type]) => refTarget(type));
  const indexes = schema.indexes();
  if (fields.length) lines.push("", "### Fields", ...fields.map(([name, type]) => fieldLine(name, type)));
  if (relations.length) lines.push("", "### Relations", ...relations.map(([name, type]) => relationLine(name, type)));
  if (indexes.length) lines.push("", "### Indexes", ...indexes.map(indexLine));
  return lines;
}

function refTarget(type) {
  return type.options?.ref ?? elementType(type)?.options?.ref ?? null;
}

// An array's element type: Mongoose 9 calls it embeddedSchemaType, and 8, which adopted projects may still run,
// calls it caster.
function elementType(type) {
  return type.embeddedSchemaType ?? type.caster;
}

function fieldLine(name, type) {
  const kind = type.instance === "Array" ? `[${elementType(type)?.instance ?? "Mixed"}]` : type.instance;
  return `- ${name}: ${kind}${flagsText(fieldFlags(type))}`;
}

function fieldFlags(type) {
  const options = type.options ?? {};
  const flags = [];
  if (type.isRequired) flags.push("required");
  if (options.unique) flags.push("unique");
  if (options.index) flags.push("index");
  if (options.select === false) flags.push("select: false");
  for (const name of ["min", "max", "minlength", "maxlength"]) {
    if (options[name] !== undefined) flags.push(`${name}=${describeValue(options[name])}`);
  }
  if (Array.isArray(options.enum)) flags.push(`enum=${options.enum.length}`);
  if (options.default !== undefined) flags.push(`default=${describeValue(options.default)}`);
  return flags;
}

function describeValue(value) {
  return typeof value === "function" ? value.name || "(fn)" : JSON.stringify(value);
}

function flagsText(flags) {
  return flags.length ? ` (${flags.join(", ")})` : "";
}

function relationLine(name, type) {
  const kind = type.instance === "Array" ? `[${elementType(type).instance}]` : type.instance;
  return `- ${name}: ${kind} → ${refTarget(type)}${flagsText(fieldFlags(type))}`;
}

function indexLine([fields, options]) {
  const on = Object.entries(fields)
    .map(([field, direction]) => `${field}:${direction}`)
    .join(", ");
  const flags = [];
  if (options?.unique) flags.push("unique");
  if (options?.sparse) flags.push("sparse");
  if (options?.partialFilterExpression) flags.push(`where ${JSON.stringify(options.partialFilterExpression)}`);
  return `- on ${on}${flagsText(flags)}`;
}

function kebabCase(name) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .toLowerCase();
}

main()
  .then((code) => process.exit(code ?? 0))
  .catch((error) => {
    console.error(`${PROG}: ${error.stack || error.message}`);
    process.exit(1);
  });
