"""Print Django apps' models as SCHEMA.md markdown: fields, relations, indexes and constraints.

Run it from the directory holding manage.py, so Django is configured first:

    python manage.py shell -v 0 -c "import runpy; runpy.run_path('/path/to/django_model_dump.py', run_name='__main__')"

`-v 0` keeps the shell's own notices (Django 5.2+ prints its auto-imports to stdout) out of the output.
KIT_APPS=properties,deals picks apps by label. The default is every project app: an app whose
directory is under settings.BASE_DIR (the working directory when BASE_DIR isn't set) and not inside
site-packages or dist-packages. The selected apps print as one document; KIT_OUT_DIR=<dir> writes
<dir>/<app_label>/SCHEMA.md per app instead. Exits 2 when Django isn't configured or an app label
is unknown.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

from django.apps import apps
from django.conf import settings
from django.db.models import NOT_PROVIDED

APPS_ENV = "KIT_APPS"
OUT_DIR_ENV = "KIT_OUT_DIR"
SCHEMA_FILENAME = "SCHEMA.md"
EXIT_USAGE_ERROR = 2
PROG = "django_model_dump"
VENDOR_DIRS = frozenset({"site-packages", "dist-packages"})
RUN_COMMAND = (
    'python manage.py shell -v 0 -c "import runpy; '
    "runpy.run_path('${CLAUDE_PLUGIN_ROOT}/scripts/django_model_dump.py', run_name='__main__')\""
)


class UsageError(Exception):
    """The dump can't run as asked; the message says what to do."""


def main() -> int:
    try:
        selected, requested = select_apps()
    except UsageError as error:
        print(f"{PROG}: {error}", file=sys.stderr)
        return EXIT_USAGE_ERROR
    out_dir = os.environ.get(OUT_DIR_ENV)
    if not out_dir:
        sys.stdout.write(render_document(selected, ",".join(requested)))
        return 0
    for config in selected:
        target = Path(out_dir) / config.label / SCHEMA_FILENAME
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render_document([config], config.label), encoding="utf-8")
        print(target)
    return 0


def select_apps() -> tuple[list, list[str]]:
    """The app configs to dump, sorted by label, and the labels KIT_APPS asked for (empty for the default)."""
    if not apps.ready:
        raise UsageError(f"Django isn't set up. Run this inside the project: {RUN_COMMAND}")
    configs = {config.label: config for config in apps.get_app_configs()}
    requested = sorted({label.strip() for label in os.environ.get(APPS_ENV, "").split(",") if label.strip()})
    unknown = [label for label in requested if label not in configs]
    if unknown:
        installed = ", ".join(sorted(configs))
        raise UsageError(f"unknown app label(s) in {APPS_ENV}: {', '.join(unknown)}. Installed: {installed}.")
    if requested:
        return [configs[label] for label in requested], requested
    root = project_root()
    selected = [config for label, config in sorted(configs.items()) if is_project_app(Path(config.path), root)]
    if not selected:
        raise UsageError(f"no project apps under {root}. Name them with {APPS_ENV}=app_a,app_b.")
    return selected, []


def project_root() -> Path:
    base_dir = getattr(settings, "BASE_DIR", None)
    return Path(base_dir or Path.cwd()).resolve()


def is_project_app(app_path: Path, root: Path) -> bool:
    resolved = app_path.resolve()
    return resolved.is_relative_to(root) and not VENDOR_DIRS.intersection(resolved.parts)


def render_document(configs: list, apps_arg: str) -> str:
    """One SCHEMA.md for these apps; `apps_arg` is the KIT_APPS value that regenerates it, empty for the default."""
    command = f"{APPS_ENV}={apps_arg} {RUN_COMMAND}" if apps_arg else RUN_COMMAND
    lines = [
        f"<!-- GENERATED by django_model_dump.py; do not edit. Regenerate: {command} > {SCHEMA_FILENAME} -->",
        f"# Schema: {', '.join(config.label for config in configs)}",
    ]
    models = [model for config in configs for model in sorted(config.get_models(), key=lambda model: model.__name__)]
    if not models:
        lines += ["", "No models."]
    for model in models:
        lines += ["", *model_lines(model)]
    return "\n".join(lines) + "\n"


def model_lines(model) -> list[str]:
    meta = model._meta
    lines = [f"## {meta.label}", f"`{model.__module__}.{model.__qualname__}`", *model_facts(meta)]
    fields = [field for field in meta.local_fields if not field.is_relation]
    relations = [field for field in (*meta.local_fields, *meta.local_many_to_many) if field.is_relation]
    sections = (
        ("Fields", [field_line(field) for field in fields]),
        (
            "Relations",
            [relation_line(field) for field in relations] + [private_line(field) for field in meta.private_fields],
        ),
        ("Indexes", [index_line(index) for index in meta.indexes]),
        ("Constraints", [constraint_line(constraint) for constraint in meta.constraints] + unique_together_lines(meta)),
    )
    for title, entries in sections:
        if entries:
            lines += ["", f"### {title}", *entries]
    return lines


def model_facts(meta) -> list[str]:
    facts = [f"- Table: `{meta.db_table}`" + ("" if meta.managed else " (unmanaged)")]
    if meta.proxy:
        facts.append(f"- Proxy of: {meta.concrete_model._meta.label}")
    parents = sorted(parent._meta.label for parent in meta.parents)
    if parents and not meta.proxy:
        facts.append(f"- Inherits (multi-table): {', '.join(parents)}")
    if meta.ordering:
        facts.append(f"- Ordering: {', '.join(str(item) for item in meta.ordering)}")
    return facts


def field_line(field) -> str:
    return f"- {field.name}: {field_type(field)}{flags_text(field_flags(field))}"


def field_type(field) -> str:
    params = [
        f"{name}={getattr(field, name)}"
        for name in ("max_length", "max_digits", "decimal_places")
        if getattr(field, name, None) is not None
    ]
    kind = type(field).__name__
    return f"{kind}({', '.join(params)})" if params else kind


def field_flags(field) -> list[str]:
    flags = [name for name in ("primary_key", "null", "blank") if getattr(field, name)]
    if field.unique and not field.primary_key:
        flags.append("unique")
    if field.db_index:
        flags.append("db_index")
    if field.has_default():
        flags.append(f"default={describe_value(field.default)}")
    db_default = getattr(field, "db_default", NOT_PROVIDED)
    if db_default is not NOT_PROVIDED:
        flags.append(f"db_default={db_default!r}")
    if field.choices:
        flags.append(f"choices={len(field.flatchoices)}")
    return flags


def describe_value(value: object) -> str:
    if callable(value):
        return f"{getattr(value, '__module__', '?')}.{getattr(value, '__qualname__', repr(value))}"
    return repr(value)


def flags_text(flags: list[str]) -> str:
    return f" ({', '.join(flags)})" if flags else ""


def relation_line(field) -> str:
    remote = field.remote_field
    details = []
    if field.many_to_one or field.one_to_one:
        details.append(f"on_delete={remote.on_delete.__name__}")
    if remote.related_name:
        details.append(f"related_name={remote.related_name}")
    else:
        details.append(f"related_name=(default) {remote.get_accessor_name()}")
    if field.many_to_many:
        through = remote.through._meta
        details.append(f"through={through.label}" + (" (auto)" if through.auto_created else ""))
    if getattr(remote, "parent_link", False):
        details.append("parent_link")
    details += field_flags(field)
    return f"- {field.name}: {type(field).__name__} → {field.related_model._meta.label}{flags_text(details)}"


def private_line(field) -> str:
    if hasattr(field, "ct_field") and hasattr(field, "fk_field"):
        return f"- {field.name}: {type(field).__name__} (ct_field={field.ct_field}, fk_field={field.fk_field})"
    target = field.related_model._meta.label if getattr(field, "related_model", None) else "?"
    return f"- {field.name}: {type(field).__name__} → {target}"


def index_line(index) -> str:
    parts = target_parts(index)
    if index.condition is not None:
        parts.append(f"where {index.condition}")
    if index.include:
        parts.append(f"include {', '.join(index.include)}")
    if index.opclasses:
        parts.append(f"opclasses {', '.join(index.opclasses)}")
    return described(index, parts)


def constraint_line(constraint) -> str:
    parts = target_parts(constraint)
    condition = constraint_condition(constraint)
    if condition is not None:
        parts.append(f"where {condition}")
    for name in ("nulls_distinct", "deferrable"):
        if getattr(constraint, name, None) is not None:
            parts.append(f"{name}={getattr(constraint, name)}")
    return described(constraint, parts)


def constraint_condition(constraint):
    """`condition`, or the instance's own `check` on Django versions before `condition` replaced it."""
    condition = getattr(constraint, "condition", None)
    return condition if condition is not None else vars(constraint).get("check")


def target_parts(item) -> list[str]:
    fields = list(getattr(item, "fields", ()))
    expressions = [str(expression) for expression in getattr(item, "expressions", ())]
    return [f"on {', '.join(fields + expressions)}"] if fields or expressions else []


def described(item, parts: list[str]) -> str:
    return " ".join([f"- {item.name}: {type(item).__name__}", *parts])


def unique_together_lines(meta) -> list[str]:
    return [f"- unique_together: {', '.join(group)}" for group in meta.unique_together]


if __name__ == "__main__":
    sys.exit(main())
