def test_running_without_the_server_s_dependencies_installed_exits_2(tmp_path):
    if shutil.which("node") is None:
        pytest.skip("node isn't installed")
    models = tmp_path / "server/src/models"
    models.mkdir(parents=True)
    (models / "tag.model.ts").write_text(TAG_MODEL)
    result = subprocess.run(["node", str(SCRIPT)], cwd=tmp_path, capture_output=True, text=True, timeout=30)
    assert result.returncode == 2
    assert "mongoose isn't installed" in result.stderr
