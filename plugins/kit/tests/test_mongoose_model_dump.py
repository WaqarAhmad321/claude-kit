import json
import shutil
import subprocess
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "mongoose_model_dump.mjs"
MONGOOSE = "mongoose@9"  # The MERN pack's major version.
SERVER_PACKAGE = {"name": "server", "private": True, "type": "module"}

TAG_MODEL = """\
import mongoose from "mongoose";

const tagSchema = new mongoose.Schema({
  label: { type: String, required: true, maxlength: 40 },
});

export const Tag = mongoose.model("Tag", tagSchema);
"""

NOTE_MODEL = """\
import mongoose from "mongoose";

const noteSchema = new mongoose.Schema(
  {
    title: { type: String, required: true, maxlength: 200 },
    status: { type: String, enum: ["draft", "published"], default: "draft" },
    owner: { type: mongoose.Schema.Types.ObjectId, ref: "User", required: true },
    tags: [{ type: mongoose.Schema.Types.ObjectId, ref: "Tag" }],
    password_hash: { type: String, select: false },
  },
  { timestamps: { createdAt: "created_at", updatedAt: "updated_at" } },
);
noteSchema.index({ owner: 1, status: 1 });

export const Note = mongoose.model("Note", noteSchema);
"""


@pytest.fixture(scope="session")
def mongoose_install(tmp_path_factory) -> Path | None:
    """A shared node_modules with mongoose installed, or None when npm or the registry isn't reachable."""
    if shutil.which("npm") is None or shutil.which("node") is None:
        return None
    root = tmp_path_factory.mktemp("mongoose-install")
    (root / "package.json").write_text(json.dumps({"name": "mongoose-model-dump-test", "private": True}))
    result = subprocess.run(
        ["npm", "install", "--no-audit", "--no-fund", MONGOOSE],
        cwd=root,
        capture_output=True,
        text=True,
        timeout=120,
    )
    return root if result.returncode == 0 else None


def mern_project(root: Path, mongoose_install: Path | None) -> Path:
    """The MERN pack's layout: the server is its own ESM package with its own node_modules, and the project root
    has neither a package.json nor node_modules."""
    if mongoose_install is None:
        pytest.skip(f"npm install {MONGOOSE} failed or npm/node/network isn't available")
    server = root / "server"
    server.mkdir(parents=True)
    (server / "package.json").write_text(json.dumps(SERVER_PACKAGE))
    shutil.copytree(mongoose_install / "node_modules", server / "node_modules")
    (server / "src/models").mkdir(parents=True)
    return root


@pytest.fixture
def project(tmp_path, mongoose_install) -> Path:
    root = mern_project(tmp_path, mongoose_install)
    (root / "server/src/models/tag.model.ts").write_text(TAG_MODEL)
    (root / "server/src/models/note.model.ts").write_text(NOTE_MODEL)
    return root


def dump(project: Path, **env: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["node", str(SCRIPT)],
        cwd=project,
        env=env,
        capture_output=True,
        text=True,
        timeout=60,
    )


def test_models_dump_as_one_document_with_fields_relations_and_indexes(project):
    result = dump(project)
    assert result.returncode == 0, result.stderr
    text = result.stdout
    assert text.startswith(
        "<!-- GENERATED by mongoose_model_dump.mjs; do not edit. Regenerate: "
        "node ${CLAUDE_PLUGIN_ROOT}/scripts/mongoose_model_dump.mjs -->\n"
    )
    assert [line for line in text.splitlines() if line.startswith("#")] == [
        "# Schema: Note, Tag",
        "## Note",
        "### Fields",
        "### Relations",
        "### Indexes",
        "## Tag",
        "### Fields",
    ]
    assert "- title: String (required, maxlength=200)" in text
    assert '- status: String (enum=2, default="draft")' in text
    assert "- password_hash: String (select: false)" in text
    assert "- owner: ObjectId → User (required)" in text
    assert "- tags: [ObjectId] → Tag" in text
    assert "- on owner:1, status:1" in text
    assert dump(project).stdout == text


def test_kit_models_dir_points_at_a_different_directory(project):
    other = project / "server/src/admin/models"
    other.mkdir(parents=True)
    (other / "tag.model.ts").write_text(TAG_MODEL)
    result = dump(project, KIT_MODELS_DIR="server/src/admin/models")
    assert result.returncode == 0, result.stderr
    assert "# Schema: Tag" in result.stdout
    assert "Note" not in result.stdout


def test_the_documented_command_writes_one_draft_per_model_into_the_project(project):
    result = dump(project, KIT_OUT_DIR=".claude/skills/_draft")
    assert result.returncode == 0, result.stderr
    drafts = [".claude/skills/_draft/note/SCHEMA.md", ".claude/skills/_draft/tag/SCHEMA.md"]
    assert sorted(result.stdout.split()) == drafts
    note = (project / ".claude/skills/_draft/note/SCHEMA.md").read_text()
    assert "# Schema: Note" in note
    assert "## Tag" not in note


