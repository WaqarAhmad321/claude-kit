@pytest.fixture
def project(tmp_path) -> Path:
    for rel, content in FILES.items():
        (tmp_path / rel).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / rel).write_text(content)
    return tmp_path


def dump(project: Path, **env: str):
    clean = {
        key: value
        for key, value in os.environ.items()
        if not key.startswith("KIT_") and key != "DJANGO_SETTINGS_MODULE"
    }
    return subprocess.run(
        [sys.executable, "manage.py", "shell", "-v", "0", "-c", RUN],
        cwd=project,
        env={**clean, **env},
        capture_output=True,
        text=True,
        timeout=120,
    )


def test_project_apps_dump_as_one_document_with_relations_indexes_and_constraints(project):
    result = dump(project)
    assert result.returncode == 0, result.stderr
    text = result.stdout
    header = text.splitlines()[0]
    assert header.startswith(
        "<!-- GENERATED by django_model_dump.py; do not edit. Regenerate: python manage.py shell -v 0 "
    )
    assert header.endswith(" > SCHEMA.md -->")
    assert "KIT_APPS" not in header
    assert [line for line in text.splitlines() if line.startswith("#")] == [
        "# Schema: catalog, orders",
        "## catalog.Product",
        "### Fields",
        "### Relations",
        "### Indexes",
        "### Constraints",
        "## catalog.Tag",
        "### Fields",
        "## orders.Order",
        "### Fields",
        "### Relations",
    ]
    assert "- status: CharField(max_length=10) (default='draft', choices=2)" in text
    assert "- tags: ManyToManyField → catalog.Tag (related_name=(default) product_set, " in text
    assert "through=catalog.Product_tags (auto), blank)" in text
    assert "- product_status_idx: Index on status, -slug" in text
    assert "- unique_live_slug: UniqueConstraint on slug where (AND: ('is_active', True))" in text
    assert "- buyer: ForeignKey → auth.User (on_delete=CASCADE, related_name=orders, db_index)" in text
    assert "- Ordering: slug" in text
    assert dump(project).stdout == text


def test_kit_apps_selects_any_installed_app_into_the_regenerate_command(project):
    result = dump(project, KIT_APPS="orders, auth")
    assert result.returncode == 0, result.stderr
    assert "Regenerate: KIT_APPS=auth,orders python manage.py shell " in result.stdout.splitlines()[0]
    assert "# Schema: auth, orders" in result.stdout
    assert "## auth.User" in result.stdout


def test_kit_out_dir_writes_one_file_per_app(project):
    result = dump(project, KIT_OUT_DIR="drafts")
    assert result.returncode == 0, result.stderr
    assert result.stdout.split() == ["drafts/catalog/SCHEMA.md", "drafts/orders/SCHEMA.md"]
    orders = (project / "drafts/orders/SCHEMA.md").read_text()
    assert "Regenerate: KIT_APPS=orders python manage.py shell " in orders.splitlines()[0]
    assert "# Schema: orders" in orders
    assert "catalog.Tag" not in orders


def test_an_unknown_app_label_exits_2(project):
    result = dump(project, KIT_APPS="nope")
    assert (result.returncode, result.stdout) == (2, "")
    assert "unknown app label(s) in KIT_APPS: nope." in result.stderr


def test_running_outside_django_exits_2(tmp_path):
    result = subprocess.run([sys.executable, str(SCRIPT)], cwd=tmp_path, capture_output=True, text=True, timeout=60)
    assert result.returncode == 2
    assert "Django isn't set up" in result.stderr
